/// Result of an AI-driven PDF -> Build extraction. Mirrors the subset of
/// fields the estimate builder needs to reconstruct an in-progress build
/// from a previously-generated PDF (invoice, estimate, or quote).
class PdfBuildExtractionResult {
  /// 'invoice' | 'estimate' | 'quote'
  final String documentType;
  final List<EstimateItem> items;
  final List<String> subsections;
  final double? depositAmount;
  final double? depositPercentage;
  final bool isDepositPercentage;
  final String? scopeSummary;
  final String? customerName;
  final String? address;
  final String? orderNumber;

  PdfBuildExtractionResult({
    required this.documentType,
    required this.items,
    required this.subsections,
    this.depositAmount,
    this.depositPercentage,
    this.isDepositPercentage = false,
    this.scopeSummary,
    this.customerName,
    this.address,
    this.orderNumber,
  });
}

/// Reconstructs an editable in-progress build from an already-generated
/// PDF (invoice/estimate/quote), for cases where the original in-progress
/// build data has been lost (e.g. SharedPreferences wiped) but the
/// finished PDF itself still exists as a job attachment/document.
///
/// Supports both known PDF layouts this app has used over time:
///  - The "old" layout: plain white boxes / simple bordered tables.
///  - The "new" layout: coloured accent bars, coloured table headers and
///    zebra-striped rows (see `_pdfStyledTable`/`_pdfSectionHeader` in
///    `estimate_builder_screen.dart`).
/// The AI prompt is written to handle either layout, since a given job may
/// have PDFs from either era, and the document type (invoice/estimate/
/// quote) is independent of which layout produced it.
class PdfToBuildService {
  /// Extracts raw text from every page of the given PDF file.
  static Future<String> extractTextFromPdf(File file) async {
    final bytes = await file.readAsBytes();
    final document = sfpdf.PdfDocument(inputBytes: bytes);
    final text = sfpdf.PdfTextExtractor(document).extractText();
    document.dispose();
    return text;
  }

  /// Runs the full PDF -> Build extraction pipeline: reads the PDF's text,
  /// sends it to AI with a layout-agnostic prompt, and parses the result
  /// into a [PdfBuildExtractionResult]. [hintedDocumentType], if provided
  /// (e.g. because the PDF came from the Invoices or Quotes/Estimates
  /// section of the job), is passed to the AI as a strong hint but the AI
  /// is still asked to confirm/override it based on the PDF content itself
  /// (title text like "INVOICE"/"ESTIMATE"/"QUOTE" or "TAX INVOICE").
  static Future<PdfBuildExtractionResult> extractBuildFromPdf(
    File pdfFile, {
    String? hintedDocumentType,
  }) async {
    final text = await extractTextFromPdf(pdfFile);
    if (text.trim().isEmpty) {
      throw Exception(
          'No readable text found in this PDF - it may be a scanned image rather than a text-based PDF.');
    }

    final rawJson = await _analyzeDocumentText(text, hintedDocumentType);
    return _parseExtractionJson(rawJson);
  }

  static Future<Map<String, dynamic>> _analyzeDocumentText(
      String text, String? hintedDocumentType) async {
    const apiKey = openAiApiKey;
    final hint = hintedDocumentType != null
        ? 'This PDF was filed under this app\'s "$hintedDocumentType" section, so it is very likely a $hintedDocumentType, but confirm this from the document\'s own title/heading text and override it if the text clearly disagrees.'
        : 'Determine the document type from the text itself.';

    final prompt = '''
You are reading a business document (invoice, estimate, or quote) PDF that was generated by an electrical contracting/trade app. The document may use one of TWO different layouts this app has used over time:

LAYOUT A ("old" - plain white box style):
- Simple bordered tables, plain black/white text, minimal styling.
- Sections may be shown as plain bold headings above a table of items.

LAYOUT B ("new" - coloured line style):
- A coloured accent bar/heading band above each section name.
- Item tables have a solid coloured header row and light alternating row shading.
- A highlighted "totals" box near the bottom for the grand total.

Either layout may represent an INVOICE, ESTIMATE, or QUOTE - the layout style is NOT related to the document type. $hint

Extract a structured JSON object with this exact shape:
{
  "document_type": "invoice" | "estimate" | "quote",
  "customer_name": string or null,
  "address": string or null,
  "order_number": string or null,
  "scope_summary": string or null,
  "sections": [
    {
      "name": string,
      "items": [
        {
          "item_name": string,
          "id_code": string or null,
          "quantity": number,
          "unit_price": number,
          "purchase_price": number or null
        }
      ]
    }
  ],
  "deposit_amount": number or null,
  "deposit_percentage": number or null,
  "is_deposit_percentage": boolean
}

Rules:
- "sections" should reflect whatever section/subsection headings appear above groups of line items in the document. If there are no explicit section headings, put all items under a single section named "Main".
- "unit_price" is the sell price shown per line item (ex-GST if the document shows GST separately, otherwise the shown price).
- "purchase_price" is usually NOT shown on customer-facing documents - leave it null unless you can clearly see a distinct cost/buy price column.
- "id_code" is any product/stock code shown next to the item name, if present; otherwise null.
- Only set "deposit_amount"/"deposit_percentage" if a deposit line or note is clearly present; otherwise leave both null and "is_deposit_percentage" false.
- Respond with ONLY the JSON object, no other commentary or markdown formatting.

Document text:
$text
''';

    final response = await http.post(
      Uri.parse('https://api.openai.com/v1/chat/completions'),
      headers: {
        'Content-Type': 'application/json',
        'Authorization': 'Bearer $apiKey',
      },
      body: jsonEncode({
        "model": "gpt-4o-mini",
        "messages": [
          {"role": "user", "content": prompt}
        ],
        "max_tokens": 3000,
        "temperature": 0,
      }),
    );

    if (response.statusCode != 200) {
      throw Exception('AI service error: ${response.body}');
    }

    final data = jsonDecode(response.body);
    final content = data['choices'][0]['message']['content'] as String;
    final cleaned = _stripMarkdownFences(content);
    try {
      return jsonDecode(cleaned) as Map<String, dynamic>;
    } catch (e) {
      throw Exception(
          'Could not parse AI response as JSON. Raw response: $cleaned');
    }
  }

  static String _stripMarkdownFences(String content) {
    var s = content.trim();
    if (s.startsWith('```')) {
      s = s.replaceFirst(RegExp(r'^```[a-zA-Z]*\n?'), '');
      if (s.endsWith('```')) {
        s = s.substring(0, s.length - 3);
      }
    }
    return s.trim();
  }

  static PdfBuildExtractionResult _parseExtractionJson(
      Map<String, dynamic> json) {
    final documentType =
        (json['document_type'] as String?)?.toLowerCase().trim();
    final normalizedType = ['invoice', 'estimate', 'quote']
            .contains(documentType)
        ? documentType!
        : 'estimate';

    final items = <EstimateItem>[];
    final subsections = <String>[];

    final sections = json['sections'];
    if (sections is List) {
      for (final sectionRaw in sections) {
        if (sectionRaw is! Map) continue;
        final sectionName =
            (sectionRaw['name'] as String?)?.trim().isNotEmpty == true
                ? sectionRaw['name'] as String
                : 'Main';
        if (!subsections.contains(sectionName)) {
          subsections.add(sectionName);
        }

        final sectionItems = sectionRaw['items'];
        if (sectionItems is! List) continue;
        for (final itemRaw in sectionItems) {
          if (itemRaw is! Map) continue;
          final name = (itemRaw['item_name'] as String?)?.trim() ?? '';
          if (name.isEmpty) continue;
          final code = (itemRaw['id_code'] as String?)?.trim() ?? '';
          final quantity = _toDouble(itemRaw['quantity']) ?? 1.0;
          final unitPrice = _toDouble(itemRaw['unit_price']) ?? 0.0;
          final purchasePrice = _toDouble(itemRaw['purchase_price']);

          items.add(EstimateItem(
            name: name,
            description: code,
            unitPrice: unitPrice,
            quantity: quantity,
            purchasePrice: purchasePrice,
            section: sectionName,
          ));
        }
      }
    }

    if (subsections.isEmpty) {
      subsections.add('Main');
    }

    return PdfBuildExtractionResult(
      documentType: normalizedType,
      items: items,
      subsections: subsections,
      depositAmount: _toDouble(json['deposit_amount']),
      depositPercentage: _toDouble(json['deposit_percentage']),
      isDepositPercentage: json['is_deposit_percentage'] == true,
      scopeSummary: (json['scope_summary'] as String?)?.trim().isEmpty == true
          ? null
          : json['scope_summary'] as String?,
      customerName: (json['customer_name'] as String?)?.trim().isEmpty == true
          ? null
          : json['customer_name'] as String?,
      address: (json['address'] as String?)?.trim().isEmpty == true
          ? null
          : json['address'] as String?,
      orderNumber: (json['order_number'] as String?)?.trim().isEmpty == true
          ? null
          : json['order_number'] as String?,
    );
  }

  static double? _toDouble(dynamic value) {
    if (value == null) return null;
    if (value is num) return value.toDouble();
    if (value is String) return double.tryParse(value);
    return null;
  }

  static String _normalizeCode(String? s) => (s ?? '')
      .replaceAll(RegExp(r'[\s\-_]+'), '')
      .replaceAll('\u200B', '')
      .replaceAll('\uFFFD', '')
      .trim()
      .toLowerCase();

  /// Fills in each extracted item's purchase (buy) price by searching the
  /// pricebook for a matching item, keyed first by ID/stock code, and only
  /// falling back to matching by exact name if no code is available or no
  /// code match is found.
  ///
  /// If a pricebook match is found, only [EstimateItem.purchasePrice] is
  /// updated from that match - everything else the AI extracted (name,
  /// quantity, sell price, section) is left completely untouched. If no
  /// match is found, the item is returned as-is (purchasePrice stays
  /// whatever the AI extracted, which per the prompt should be null in
  /// virtually all cases since buy prices aren't printed on customer PDFs).
  /// Nothing is ever guessed or invented here - it's a straight lookup.
  static List<EstimateItem> applyPricebookBuyPrices({
    required List<EstimateItem> items,
    required List<PriceBookItem> priceBook,
  }) {
    // Build lookup maps once for O(1) matching instead of O(n*m).
    final byCode = <String, PriceBookItem>{};
    final byName = <String, PriceBookItem>{};
    for (final pb in priceBook) {
      final code = _normalizeCode(pb.code);
      if (code.isNotEmpty && !byCode.containsKey(code)) {
        byCode[code] = pb;
      }
      final name = _normalizeCode(pb.name);
      if (name.isNotEmpty && !byName.containsKey(name)) {
        byName[name] = pb;
      }
    }

    return items.map((item) {
      final code = _normalizeCode(item.description);
      final name = _normalizeCode(item.name);

      final match = (code.isNotEmpty ? byCode[code] : null) ??
          (code.isNotEmpty ? byName[code] : null) ??
          (name.isNotEmpty ? byCode[name] : null) ??
          (name.isNotEmpty ? byName[name] : null);

      if (match == null) return item;
      return item.copyWith(purchasePrice: match.purchasePrice);
    }).toList();
  }
}
